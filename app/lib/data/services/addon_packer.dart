import 'dart:convert';
import 'dart:io';

import 'package:archive/archive_io.dart';
import 'package:flutter/services.dart' show AssetManifest, rootBundle;
import 'package:path/path.dart' as p;

import '../../core/constants.dart';
import '../../domain/formats/mcstructure_codec.dart';
import '../../domain/model/design.dart';

/// One design to embed in the exported pack.
class PackDesign {
  const PackDesign({
    required this.id,
    required this.name,
    required this.design,
    required this.droppedBlocks,
    required this.sourceFormat,
  });

  final String id;
  final String name;
  final Design design;
  final int droppedBlocks;
  final String sourceFormat;

  Map<String, Object?> miniReport() => {
        'format': sourceFormat,
        'size': [
          design.dimensions.$1, design.dimensions.$2, design.dimensions.$3,
        ],
        'blocks': design.blocks.length,
        'palette': design.palette.length,
        'dropped': droppedBlocks,
      };
}

/// Builds a `.mcaddon` (zip container) from the bundled pack template +
/// embedded designs — the same layout `scripts/build_addon.py` produces, so
/// `validate_addon.py` semantics apply to app exports as well.
///
/// Security: design ids sanitized to `[a-z0-9_]`; template files come only
/// from the app's own assets; nothing executable is generated.
class AddonPacker {
  const AddonPacker();

  static final RegExp _safeId = RegExp(r'[^a-z0-9_]+');

  static String sanitizeId(String raw) {
    var out = raw.toLowerCase().replaceAll(_safeId, '_');
    out = out.replaceAll(RegExp(r'^_+|_+$'), '');
    if (out.length > 40) out = out.substring(0, 40);
    return out.isEmpty ? 'design' : out;
  }

  /// Extract the embedded template (from assets) into [workDir] and write
  /// design modules + mcstructures; returns the pack dirs map.
  Future<Map<String, String>> stageTemplate(Directory workDir) async {
    final bp = Directory(p.join(workDir.path, 's3d_builder_bp'))
      ..createSync(recursive: true);
    final rp = Directory(p.join(workDir.path, 's3d_builder_rp'))
      ..createSync(recursive: true);

    final manifest = await AssetManifest.loadFromAssetBundle(rootBundle);
    final assetPaths = manifest
        .listAssets()
        .where((a) => a.startsWith('$kAddonTemplateAssetRoot/'))
        .toList(growable: false);
    if (assetPaths.isEmpty) {
      throw StateError('addon template assets missing — run '
          'tool/sync_addon_template.dart / CI step before building');
    }
    for (final asset in assetPaths) {
      final rel = asset.substring('$kAddonTemplateAssetRoot/'.length);
      final target = p.join(
          rel.startsWith('bp/') ? bp.path : rp.path, rel.substring(3));
      final file = File(target);
      file.parent.createSync(recursive: true);
      final byteData = await rootBundle.load(asset);
      await file.writeAsBytes(
          byteData.buffer.asUint8List(byteData.offsetInBytes, byteData.lengthInBytes),
          flush: false);
    }
    return {'bp': bp.path, 'rp': rp.path};
  }

  Future<void> embedDesigns(Directory bpDir, List<PackDesign> designs) async {
    final dataDir = Directory(p.join(bpDir.path, 'scripts', 's3d', 'data'))
      ..createSync(recursive: true);
    final structDir =
        Directory(p.join(bpDir.path, 'structures', 's3d'))
      ..createSync(recursive: true);

    final indexItems = <Map<String, Object?>>[];
    final blocks = <String, Object?>{};
    final used = <String>{};
    final modules = <String>[];

    for (var i = 0; i < designs.length; i++) {
      final d = designs[i];
      var did = sanitizeId(d.id);
      if (used.contains(did)) did = '${did}_${used.length}';
      used.add(did);

      final payload = Map<String, Object?>.from(d.design.toJson())..['id'] = did;
      final body = const JsonEncoder().convert(payload);
      File(p.join(dataDir.path, '$did.js'))
          .writeAsStringSync('// generated by Schematic 3D app — do not edit\n'
              'export const DESIGN = $body;\n');

      indexItems.add({
        'id': did,
        'name': d.name,
        'module': './$did.js',
        'dimensions': [
          d.design.dimensions.$1, d.design.dimensions.$2, d.design.dimensions.$3,
        ],
        'blockCount': d.design.blocks.length,
      });
      blocks[did] = d.miniReport();
      modules.add('import { DESIGN as d$i } from "./$did.js";');

      // .mcstructure twin for manual `/structure save` / import tests
      final mc = McstructureCodec.encode(d.design);
      File(p.join(structDir.path, '$did.mcstructure'))
          .writeAsBytesSync(mc, flush: false);
    }

    File(p.join(dataDir.path, 'manifest.json')).writeAsStringSync(
        const JsonEncoder.withIndent(' ').convert(
            {'designs': indexItems, 'blocks': blocks}));

    final indexJs = modules.isEmpty
        ? 'export const DESIGNS = [];\n'
        : '${modules.join('\n')}\n'
            'export const DESIGNS = [${List.generate(designs.length, (i) => 'd$i').join(',')}];\n';
    File(p.join(dataDir.path, 'index.js')).writeAsStringSync(
        '// generated by Schematic 3D app — do not edit\n$indexJs');
  }

  Future<File> pack(Directory workDir, File mcaddonOut) async {
    final encoder = ZipFileEncoder();
    encoder.create(mcaddonOut.path);
    for (final packDir in workDir
        .listSync()
        .whereType<Directory>()
        .where((d) => d.path.endsWith('s3d_builder_bp') || d.path.endsWith('s3d_builder_rp'))) {
      for (final f in packDir.listSync(recursive: true).whereType<File>()) {
        final rel = p.relative(f.path, from: workDir.path);
        await encoder.addFile(f, rel);
      }
    }
    encoder.close();
    return mcaddonOut;
  }

  /// Full pipeline: stage template, embed designs, zip into
  /// `<outDir>/<name>.mcaddon`, return the file. The caller owns `outDir`.
  Future<File> build({
    required String outName,
    required List<PackDesign> designs,
    required Directory outDir,
  }) async {
    final tmp = Directory.systemTemp.createTempSync('s3d_addon_');
    try {
      final dirs = await stageTemplate(tmp);
      await embedDesigns(Directory(dirs['bp']!), designs);
      final out = File(p.join(outDir.path,
          outName.endsWith('.mcaddon') ? outName : '$outName.mcaddon'));
      out.parent.createSync(recursive: true);
      if (out.existsSync()) out.deleteSync();
      return await pack(tmp, out);
    } finally {
      try {
        tmp.deleteSync(recursive: true);
      } catch (_) {}
    }
  }
}
