"""Pack designs into a ready-to-import `.mcaddon` for Schematic 3D Builder.

The add-on templates live in `bedrock_addon/` (single source of truth). This
module:
  1. copies BP+RP,
  2. bakes each design as an ESM data module `scripts/s3d/data/<id>.js`,
  3. regenerates `scripts/s3d/data/index.js` (the in-game design list),
  4. patches manifest version strings (never the UUIDs — those are generated
     once and committed so dependencies stay stable),
  5. zips as `<name>.mcaddon` (zip container, manifest at BP/RP roots).

Security notes: design ids are sanitized to [a-z0-9_]; nothing is executed
from imported files; the zip only contains generated files from our own
templates.
"""
from __future__ import annotations

import json
import re
import shutil
import uuid as uuidlib
import zipfile
from dataclasses import dataclass
from pathlib import Path

from ..models import Design
from ..parsers.any import load_any

SAFE_ID_RE = re.compile(r"^[a-z0-9_]{1,40}$")


@dataclass
class BakedDesign:
    id: str
    name: str
    design: Design


def sanitize_id(raw: str) -> str:
    out = re.sub(r"[^a-z0-9_]+", "_", raw.lower()).strip("_")
    return out[:40] or "design"


def _design_to_js(design: Design, design_id: str) -> str:
    payload = design.to_json_dict()
    payload["id"] = design_id
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    return ("// generated by schematic3d_converter — do not edit\n"
            f"export const DESIGN = {body};\n")


def bake(addon_dir: Path, designs: list[tuple[str, Path]], out_dir: Path,
         *, pack_version: tuple[int, int, int] = (1, 0, 0),
         also_mcstructures: bool = True) -> Path:
    """Copy templates + designs and return the built .mcaddon path.

    designs: list of (human id, file path).
    """
    addon_dir = Path(addon_dir)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    work = out_dir / "_pack_work"
    if work.exists():
        shutil.rmtree(work)
    shutil.copytree(addon_dir / "behavior_pack", work / "s3d_builder_bp")
    shutil.copytree(addon_dir / "resource_pack", work / "s3d_builder_rp")

    data_dir = work / "s3d_builder_bp" / "scripts" / "s3d" / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    index_items = []
    used_ids: set[str] = set()
    manifest_blocks: dict[str, dict] = {}
    struct_dir = work / "s3d_builder_bp" / "structures" / "s3d"
    for human, path in designs:
        design, rep, conv, fmt = load_any(Path(path))
        if not rep.ok:
            raise ValueError(f"design {path} failed validation: "
                             f"{[i.message for i in rep.errors][:4]}")
        did = sanitize_id(human or path.stem)
        if did in used_ids:
            did = f"{did}_{len(used_ids)}"
        used_ids.add(did)
        (data_dir / f"{did}.js").write_text(_design_to_js(design, did),
                                            encoding="utf-8")
        index_items.append({
            "id": did, "name": design.name,
            "module": f"./{did}.js",
            "dimensions": list(design.dimensions),
            "blockCount": design.block_count,
        })
        manifest_blocks[did] = build_report_mini(design, fmt)
        if also_mcstructures and path.suffix.lower() != ".mcstructure":
            from .mcstructure_out import write_file
            struct_dir.mkdir(parents=True, exist_ok=True)
            write_file(design, struct_dir / f"{did}.mcstructure")

    (data_dir / "manifest.json").write_text(
        json.dumps({"designs": index_items, "blocks": manifest_blocks},
                   ensure_ascii=False, indent=1), encoding="utf-8")
    modules = []
    for i, item in enumerate(index_items):
        modules.append(f'import {{ DESIGN as d{i} }} from "{item["module"]}";')
    modules.append("export const DESIGNS = [" +
                   ",".join(f"d{i}" for i in range(len(index_items))) + "];")
    (data_dir / "index.js").write_text(
        "// generated by schematic3d_converter — do not edit\n" +
        "\n".join(modules if index_items else
                  ["export const DESIGNS = [];"]) + "\n", encoding="utf-8")

    for pack in ("s3d_builder_bp", "s3d_builder_rp"):
        _patch_version(work / pack, pack_version)

    mcaddon = out_dir / "Schematic3DBuilder.mcaddon"
    with zipfile.ZipFile(mcaddon, "w", zipfile.ZIP_DEFLATED) as z:
        for root in sorted(work.iterdir()):
            if root.is_dir():
                for f in sorted(root.rglob("*")):
                    if f.is_file():
                        z.write(f, f.relative_to(work))
    shutil.rmtree(work)
    return mcaddon


def build_report_mini(design: Design, fmt: str) -> dict:
    from ..resources import material_summary
    ms = material_summary(design)
    return {
        "format": fmt,
        "blockCount": design.block_count,
        "materialCount": ms.material_blocks,
        "topMaterials": [[r.id, r.count] for r in ms.rows[:8]],
    }


def _patch_version(pack_dir: Path, version: tuple[int, int, int]):
    mf = pack_dir / "manifest.json"
    text = mf.read_text(encoding="utf-8")
    ver = list(version)
    text = text.replace('"__PACK_VERSION__"', json.dumps(ver))
    # sub-module versions follow header version for simplicity
    text = text.replace('"__MODULE_VERSION__"', json.dumps([version[0], version[1], version[2]]))
    text = text.replace('"__RP_VERSION__"', json.dumps(ver))
    mf.write_text(text, encoding="utf-8")


def new_uuid() -> str:
    return str(uuidlib.uuid4())
